export function собратьПромптыСбора(сыраяФорма) {
    const форма = нормализоватьФорму(сыраяФорма);
    const оценка = форма.режимБюджета === 'оценка';
    const фильтрВиз = нужныПравилаВиз(форма);

    const правилоБюджета = оценка
        ? 'РЕЖИМ ОЦЕНКИ СТОИМОСТИ: пользователь НЕ задал максимальный бюджет. Не выдумывай потолок и не меняй направление из-за цены. Посчитай реалистичную рыночную стоимость (перелёты + проживание) на ВСЕХ туристов в рублях. Дай три варианта разного уровня цены. '
        : 'ПРАВИЛО БЮДЖЕТА: budget — желаемая суммарная стоимость на ВСЕХ туристов в рублях. Большинство вариантов уложи в budget. 1–2 можно чуть дороже, но не более чем на 10%. ';

    const правилоНаправления = оценка
        ? 'ЖЁСТКОЕ ПРАВИЛО НАПРАВЛЕНИЯ: если страна заполнена (режимКуда="знаю") — оставайся в этом направлении/регионе. Для Азии — только Азия, не Дубай/ОАЭ/Турция/Европа. Три разные страны внутри региона. '
        : 'ЖЁСТКОЕ ПРАВИЛО НАПРАВЛЕНИЯ: если страна заполнена — сначала уложись туда. Не прыгай на другой континент. Для Азии не предлагай Турцию, Дубай, ОАЭ, Европу. ';

    const правилоВиз = фильтрВиз
        ? 'ЖЁСТКОЕ ПРАВИЛО ВИЗ: visaRequirement — разрешённые режимы для гражданина РФ. Предлагай только подходящие страны. "Без виз" — строго безвизовые; не предлагай Шенген, США, Японию, Китай, Австралию и прочие визовые без «Готов оформить визу». '
        : 'ПРАВИЛО ВИЗ: пользователь сам указал конкретные страны — не отсекай их из‑за виз. ';

    const самопроверка = оценка
        ? (фильтрВиз
            ? 'САМОПРОВЕРКА: стоимость реалистична; виза входит в visaRequirement. '
            : 'САМОПРОВЕРКА: стоимость реалистична. ')
        : (фильтрВиз
            ? 'САМОПРОВЕРКА: стоимостьВсего ≤ budget×1.1; большинство ≤ budget; виза в visaRequirement. '
            : 'САМОПРОВЕРКА: стоимостьВсего ≤ budget×1.1; большинство ≤ budget. ');

    const системныйПромпт = 'Ты — тревел-эксперт. Планируешь поездки для ГРАЖДАНИНА РОССИИ (паспорт РФ). ' +
        'Предложи минимум ТРИ РАЗНЫХ варианта в РАЗНЫХ странах. ' +
        правилоБюджета +
        'Все цены — на всех туристов сразу. ' +
        правилоВиз +
        правилоНаправления +
        'Учитывай specialRequests только если они не пустые. ' +
        'Хронология этапа: перелёт прибытия → 3 отеля → следующий этап; обратный перелёт только у последнего этапа. ' +
        схемаJsonСобрать() +
        'Поле погода НЕ заполняй. Не пиши метро, если не просили. Пиши кратко. Без markdown вне JSON. ' +
        самопроверка +
        (форма.baggageIncluded ? 'Все перелёты с багажом. ' : '');

    const ограничения = [];
    if (оценка) {
        ограничения.push('Бюджет не задан: оцени реалистичную стоимость трёх поездок');
    } else if (форма.бюджет) {
        ограничения.push('Желаемый бюджет на всех: ' + форма.бюджет +
            ' ₽. Большинство не дороже; 1–2 до +10% (потолок ' + Math.round(форма.бюджет * 1.1) + ' ₽)');
    }
    if (форма.страна && форма.режимКуда === 'знаю') {
        ограничения.push('Направление: ' + форма.страна + ' — оставайся в нём; другой континент запрещён');
        const сж = сжать(форма.страна);
        if (сж.indexOf('европ') !== -1) {
            ограничения.push('Только Европа');
        }
        if (сж === 'азия' || сж.indexOf('азиат') !== -1 || сж === 'asia') {
            ограничения.push('Только Азия; не Дубай, не ОАЭ, не Турция');
        }
        if (сж.indexOf('афри') !== -1) {
            ограничения.push('Только Африка');
        }
        if (сж.indexOf('америк') !== -1 || сж.indexOf('кариб') !== -1) {
            ограничения.push('Только Америка');
        }
        if (сж.indexOf('океан') !== -1 || сж.indexOf('австрал') !== -1) {
            ограничения.push('Только Океания');
        }
        if (сж.indexOf('кавказ') !== -1) {
            ограничения.push('Только Кавказ');
        }
    }
    if (естьИнтерес(форма, 'Море')) {
        const сж = сжать(форма.страна || '');
        if (сж.indexOf('европ') !== -1 && фильтрВиз &&
            !(форма.visaRequirement || []).includes('Готов оформить визу')) {
            ограничения.push('Море в Европе без визы: Черногория, Албания, Босния; не Шенген');
        } else if (сж === 'азия' || сж.indexOf('азиат') !== -1) {
            ограничения.push('Море в Азии: любой азиатский пляж; не Дубай');
        } else {
            ограничения.push('Каждый этап — пляжный отдых; города без пляжа запрещены');
        }
    }
    if (фильтрВиз && форма.visaRequirement.length > 0) {
        ограничения.push('Визовые режимы: ' + форма.visaRequirement.join(', '));
        if (форма.visaRequirement.indexOf('Готов оформить визу') === -1) {
            ограничения.push('Запрещены страны с заранее оформляемой визой для РФ');
        }
    } else if (!фильтрВиз) {
        ограничения.push('Конкретные страны пользователя — визовый фильтр не применять');
    }
    if (пользовательБезДождей(форма)) {
        ограничения.push('Пользователь просил без дождей — не предлагай сезон дождей');
    }

    const задача = оценка
        ? 'Оцени стоимость 3–5 реалистичных поездок в РАЗНЫХ странах.'
        : 'Подбери 3–5 вариантов в РАЗНЫХ странах.';

    const пользовательскийПромпт = задача +
        (ограничения.length ? ' ЖЁСТКИЕ ОГРАНИЧЕНИЯ: ' + ограничения.join('; ') + '.' : '') +
        ' Данные пользователя: ' + JSON.stringify(форма) + '.';

    return {
        форма: форма,
        системныйПромпт: системныйПромпт,
        пользовательскийПромпт: пользовательскийПромпт,
        нужноМоре: естьИнтерес(форма, 'Море'),
        направление: форма.режимКуда === 'знаю' ? форма.страна : '',
        режимыВизы: фильтрВиз
            ? (форма.visaRequirement.length ? форма.visaRequirement : ['Без виз'])
            : ['Готов оформить визу']
    };
}

export function собратьПромптыИзменения(параметры) {
    const текст = String((параметры && параметры.изменение) || '').slice(0, 2000);
    const добавляемГород = /добав.*(город|этап)|ещё один город|еще один город|новый город/i.test(текст);
    const маршрут = параметры && параметры.текущийМаршрут;
    const сжатые = {
        варианты: ((маршрут && маршрут.варианты) || []).slice(0, 8).map(function (вариант, номер) {
            return {
                номер: номер + 1,
                маршрутКратко: String(вариант.маршрутКратко || '').slice(0, 200),
                стоимостьВсего: Number(вариант.стоимостьВсего) || 0,
                этапы: ((вариант.этапы) || []).slice(0, 8).map(function (этап) {
                    return {
                        место: String(этап.место || '').slice(0, 80),
                        дни: Number(этап.дни) || 1,
                        датаОт: String(этап.датаОт || '').slice(0, 32),
                        датаДо: String(этап.датаДо || '').slice(0, 32),
                        описание: String(этап.описание || '').slice(0, 200)
                    };
                })
            };
        })
    };
    const бюджет = маршрут && маршрут.бюджет;
    const оценка = маршрут && маршрут.режимБюджета === 'оценка';

    const системныйПромпт = добавляемГород
        ? 'Ты — тревел-эксперт. Пользователь просит ДОБАВИТЬ ГОРОД В МАРШРУТ — новый этап в цепочке. ' +
            'В каждом варианте городов станет на один больше. Тот же регион. Пересчитай дни, перелёты, отели, стоимость. ' +
            'Обратный перелёт только у последнего этапа. Верни JSON с полем варианты. Метро не выдумывай.'
        : 'Ты — тревел-эксперт. Пользователь просит изменить варианты. Верни JSON с полем варианты в том же формате. Метро не выдумывай.';

    const пользовательскийПромпт = добавляемГород
        ? 'Текущие маршруты: ' + JSON.stringify(сжатые) +
            '. Просьба: ' + текст +
            '. Добавь город во ВСЕ варианты.' +
            (оценка ? ' Оценка стоимости — пересчитай.' :
                (бюджет ? ' Бюджет ' + бюджет + ' ₽, не больше +10%.' : ''))
        : 'Текущие варианты: ' + JSON.stringify(сжатые) +
            '. Просьба: ' + текст +
            '. Измени ВСЕ варианты, сохрани число вариантов и длительность.' +
            (оценка ? ' Оценка стоимости.' :
                (бюджет ? ' Бюджет ' + бюджет + ' ₽, не больше +10%.' : ''));

    const форма = нормализоватьФорму(параметры && параметры.форма);
    const фильтрВиз = нужныПравилаВиз(форма);
    return {
        форма: форма,
        системныйПромпт: системныйПромпт,
        пользовательскийПромпт: пользовательскийПромпт,
        нужноМоре: естьИнтерес(форма, 'Море'),
        направление: форма.режимКуда === 'знаю' ? форма.страна : '',
        режимыВизы: фильтрВиз
            ? (форма.visaRequirement.length ? форма.visaRequirement : ['Без виз'])
            : ['Готов оформить визу'],
        неФильтроватьСтрану: добавляемГород || !!(параметры && параметры.неФильтроватьСтрану),
        добавляемГород: добавляемГород
    };
}
