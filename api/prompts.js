// Доверенные промпты живут только здесь. Клиент шлёт поля формы, не текст system.

function сжать(текст) {
    return String(текст || '')
        .toLowerCase()
        .replace(/ё/g, 'е')
        .replace(/[^a-zа-я0-9]+/g, '');
}

const ЧИСТЫЕ_РЕГИОНЫ = [
    'европа', 'europe', 'азия', 'asia', 'азиатский', 'африка', 'africa',
    'ближнийвосток', 'middleeast', 'кавказ', 'кариб', 'карибы',
    'америка', 'america', 'латинскаяамерика', 'южнаяамерика', 'севернаяамерика',
    'океания', 'юговосточнаяазия', 'юва', 'средиземномор', 'средиземноморье'
];

function этоТолькоРегион(запрос) {
    const текст = String(запрос || '').trim();
    if (!текст) {
        return false;
    }
    const целый = сжать(текст);
    if (ЧИСТЫЕ_РЕГИОНЫ.some(function (р) { return целый === сжать(р); })) {
        return true;
    }
    const части = String(текст)
        .toLowerCase()
        .split(/\s*(?:,|;|\/|\+| и | или | and | or )\s*/i)
        .map(function (ч) { return сжать(ч); })
        .filter(Boolean);
    if (части.length === 0) {
        return false;
    }
    return части.every(function (часть) {
        return ЧИСТЫЕ_РЕГИОНЫ.some(function (р) { return часть === сжать(р); });
    });
}

function нужныПравилаВиз(форма) {
    if (!форма || форма.режимКуда !== 'знаю') {
        return true;
    }
    const страна = String(форма.страна || '').trim();
    if (!страна) {
        return true;
    }
    return этоТолькоРегион(страна);
}

function естьИнтерес(форма, имя) {
    return Array.isArray(форма && форма.интересы) && форма.интересы.indexOf(имя) !== -1;
}

function пользовательБезДождей(форма) {
    const текст = String((форма && форма.specialRequests) || '').toLowerCase();
    return текст.indexOf('без дожд') !== -1 ||
        текст.indexOf('без осадк') !== -1 ||
        текст.indexOf('не дожд') !== -1;
}

function нормализоватьФорму(сырая) {
    const ф = сырая && typeof сырая === 'object' ? сырая : {};
    const визы = Array.isArray(ф.visaRequirement) ? ф.visaRequirement.map(String).slice(0, 8) : [];
    return {
        откуда: String(ф.откуда || 'Москва').slice(0, 80),
        датаНачала: String(ф.датаНачала || '').slice(0, 32),
        датаВозврата: String(ф.датаВозврата || '').slice(0, 32),
        продолжительность: Number(ф.продолжительность) || 7,
        режимБюджета: ф.режимБюджета === 'оценка' ? 'оценка' : 'лимит',
        бюджет: ф.бюджет == null ? null : Number(ф.бюджет),
        режимКуда: ф.режимКуда === 'знаю' ? 'знаю' : 'предложите',
        страна: String(ф.страна || '').slice(0, 120),
        интересы: Array.isArray(ф.интересы) ? ф.интересы.map(String).slice(0, 12) : [],
        темп: String(ф.темп || '').slice(0, 40),
        комфорт: String(ф.комфорт || '').slice(0, 40),
        adults: Math.min(10, Math.max(1, Number(ф.adults) || 1)),
        children2_12: Math.min(10, Math.max(0, Number(ф.children2_12) || 0)),
        children0_2: Math.min(10, Math.max(0, Number(ф.children0_2) || 0)),
        visaRequirement: визы,
        specialRequests: String(ф.specialRequests || '').slice(0, 2000),
        baggageIncluded: !!ф.baggageIncluded
    };
}

