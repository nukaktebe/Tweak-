function частиЗапросаНаправления(запрос) {
    return String(запрос || '')
        .toLowerCase()
        .split(/\s*(?:,|;|\/|\+| и | или | and | or )\s*/i)
        .map(function (часть) { return сжатьМесто(часть); })
        .filter(function (часть) { return часть.length >= 3; });
}

function маркерыСтраныЗапроса(запрос) {
    const сжатый = сжатьМесто(запрос);
    if (!сжатый) {
        return null;
    }
    const фрагменты = частиЗапросаНаправления(запрос);
    const ключиПоиска = фрагменты.length > 1 ? фрагменты : [сжатый];
    const собрано = [];
    const уже = {};

    function добавить(список) {
        (список || []).forEach(function (маркер) {
            const ключМаркера = сжатьМесто(маркер);
            if (!ключМаркера || уже[ключМаркера]) {
                return;
            }
            уже[ключМаркера] = true;
            собрано.push(маркер);
        });
    }

    ключиПоиска.forEach(function (фрагмент) {
        Object.keys(СТРАНЫ).forEach(function (ключ) {
            if (фрагмент === ключ || фрагмент.indexOf(ключ) !== -1 ||
                (фрагмент.length >= 4 && ключ.indexOf(фрагмент) !== -1)) {
                добавить(СТРАНЫ[ключ]);
                return;
            }
            if (СТРАНЫ[ключ].some(function (маркер) {
                const м = сжатьМесто(маркер);
                return фрагмент === м || (м.length >= 4 && фрагмент.indexOf(м) !== -1);
            })) {
                добавить(СТРАНЫ[ключ]);
            }
        });
    });
    return собрано.length ? собрано : null;
}

function местоПодходит(сжатоеМесто, описание) {
    if (!описание.регион && описание.тип !== 'другое') {
        return false;
    }
    if (описание.тип === 'страна') {
        const свои = маркерыСтраныЗапроса(описание.запрос);
        if (свои) {
            return свои.some(function (маркер) {
                return естьМаркер(сжатоеМесто, маркер);
            });
        }
        const ключ = сжатьМесто(описание.запрос);
        return !!(ключ && естьМаркер(сжатоеМесто, ключ));
    }
    if (описание.тип === 'другое') {
        const ключ = сжатьМесто(описание.запрос);
        return !!(ключ && естьМаркер(сжатоеМесто, ключ));
    }
    if (кодЧужогоРегиона(сжатоеМесто, описание.регион)) {
        return false;
    }
    return местоИзРегиона(сжатоеМесто, описание.регион);
}

export function вариантСоответствуетНаправлению(вариант, запрос) {
    const описание = определитьНаправление(запрос);
    if (!описание.тип) {
        return true;
    }
    const места = местаЭтапов(вариант);
    if (места.length === 0) {
        return false;
    }
    return места.every(function (место) {
        return местоПодходит(место, описание);
    });
}

export function отфильтроватьВариантыПоНаправлению(варианты, запрос) {
    if (!запрос || !Array.isArray(варианты)) {
        return варианты || [];
    }
    const описание = определитьНаправление(запрос);
    if (!описание.тип) {
        return варианты;
    }
    return варианты.filter(function (вариант) {
        return вариантСоответствуетНаправлению(вариант, запрос);
    });
}

export function кодРегионаДляСлотов(запрос) {
    const описание = определитьНаправление(запрос);
    if (описание.регион) {
        return описание.регион;
    }
    if (описание.тип === 'другое') {
        return 'другое';
    }
    return '';
}
