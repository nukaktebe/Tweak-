function естьМаркер(сжатыйТекст, маркер) {
    const м = сжатьМесто(маркер);
    if (!м || !сжатыйТекст) {
        return false;
    }
    if (м.length < 4) {
        return сжатыйТекст === м || сжатыйТекст.indexOf(м) === 0;
    }
    return сжатыйТекст.indexOf(м) !== -1;
}

function местоИзРегиона(сжатоеМесто, код) {
    const регион = РЕГИОНЫ[код];
    if (!регион || !сжатоеМесто) {
        return false;
    }
    return регион.маркеры.some(function (маркер) {
        return естьМаркер(сжатоеМесто, маркер);
    });
}

function кодЧужогоРегиона(сжатоеМесто, свойКод) {
    const ключи = Object.keys(РЕГИОНЫ);
    for (let i = 0; i < ключи.length; i++) {
        const код = ключи[i];
        if (код === свойКод) {
            continue;
        }
        if (местоИзРегиона(сжатоеМесто, код)) {
            return код;
        }
    }
    return '';
}

export function определитьНаправление(запрос) {
    const сжатый = сжатьМесто(запрос);
    if (!сжатый) {
        return { тип: '', регион: '', запрос: '' };
    }
    const коды = Object.keys(РЕГИОНЫ);
    for (let i = 0; i < коды.length; i++) {
        const код = коды[i];
        const имена = РЕГИОНЫ[код].имена;
        for (let j = 0; j < имена.length; j++) {
            const имя = сжатьМесто(имена[j]);
            if (сжатый === имя || сжатый.indexOf(имя) !== -1) {
                return { тип: 'регион', регион: код, запрос: запрос };
            }
        }
    }
    for (let i = 0; i < коды.length; i++) {
        const код = коды[i];
        if (местоИзРегиона(сжатый, код)) {
            return { тип: 'страна', регион: код, запрос: запрос };
        }
    }
    return { тип: 'другое', регион: '', запрос: запрос };
}

function местаЭтапов(вариант) {
    const места = [];
    ((вариант && вариант.этапы) || []).forEach(function (этап) {
        const сырое = String((этап && этап.место) || '').trim();
        if (!сырое) {
            return;
        }
        const сжатое = сжатьМесто(сырое);
        if (!сжатое || сжатое === 'москва' || сжатое.indexOf('москва') === 0) {
            return;
        }
        места.push(сжатое);
    });
    return места;
}

