/**
 * Достаёт JSON из ответа модели: снимает обёртку ```json, берёт
 * содержимое от первой { до последней }. Модели часто добавляют
 * пояснения вокруг JSON — без этого разбор падает.
 */
function извлечьJSON(текст) {
    if (!текст || typeof текст !== 'string') {
        return null;
    }
    let очищенный = текст.trim();
    const блокКода = очищенный.match(/```(?:json)?\s*([\s\S]*?)```/i);
    if (блокКода && блокКода[1]) {
        очищенный = блокКода[1].trim();
    }
    try {
        return JSON.parse(очищенный);
    } catch (e1) {
        const начало = очищенный.indexOf('{');
        const конец = очищенный.lastIndexOf('}');
        if (начало !== -1 && конец > начало) {
            try {
                return JSON.parse(очищенный.slice(начало, конец + 1));
            } catch (e2) {
                return null;
            }
        }
        return null;
    }
}

