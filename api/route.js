async function набратьСлоты(параметры) {
    const слоты = параметры.слоты || [];
    const копилка = [];
    const ошибки = [];
    let пояснениеНаправления = '';
    const общийСтоп = new AbortController();
    let готово = function () {};
    let ужеГотово = false;
    const ждемГотово = new Promise(function (разрешить) {
        готово = function () {
            if (ужеГотово) {
                return;
            }
            ужеГотово = true;
            разрешить();
        };
    });
    let пауза = null;

    function уникальныеСейчас() {
        let список = уникальныеВарианты(копилка);
        if (параметры.направление) {
            список = отфильтроватьВариантыПоНаправлению(список, параметры.направление);
        }
        if (параметры.режимыВизы) {
            список = отфильтроватьВариантыПоВизам(список, параметры.режимыВизы);
        }
        return список;
    }

    function проверитьНабор() {
        const есть = уникальныеСейчас();
        if (есть.length >= параметры.максимум) {
            готово();
            return;
        }
        if (есть.length >= параметры.минимум && !пауза) {
            пауза = setTimeout(готово, 3000);
        }
    }

    const хвост = ' Сейчас нужен РОВНО ОДИН короткий вариант JSON. Без markdown.' +
        (параметры.направление
            ? ' СТРОГО ' + параметры.направление + ', другие регионы запрещены.'
            : '') +
        (пропускатьФильтрВизы(параметры.режимыВизы)
            ? ''
            : ' Только страны, куда гражданин РФ въезжает по выбранному визовому режиму. Это правило для ВСЕХ стран мира, не только Европы: куда нужна заранее оформленная виза (Шенген, США, Великобритания, Китай, Япония, Австралия, Канада и любые другие на любом континенте) — запрещены, если не выбран «Готов оформить визу».');

    const задачи = слоты.map(function (слот) {
        return вызватьМодель(
            параметры.ключ,
            параметры.модель,
            параметры.системныйПромпт + хвост,
            параметры.пользовательскийПромпт + ' ' + слот.роль,
            2200,
            параметры.мсСлота,
            общийСтоп.signal
        ).then(function (ответ) {
            if (общийСтоп.signal.aborted) {
                return;
            }
            достатьВсеВарианты(ответ).forEach(function (вариант) {
                копилка.push(вариант);
            });
            if (ответ && ответ.пояснениеНаправления && !пояснениеНаправления) {
                пояснениеНаправления = ответ.пояснениеНаправления;
            }
            проверитьНабор();
        }).catch(function (ошибка) {
            if (ошибка && (ошибка.message === 'ИИ не ответил вовремя' || ошибка.name === 'AbortError')) {
                return;
            }
            ошибки.push(ошибка && ошибка.message ? ошибка.message : String(ошибка));
        });
    });

    await Promise.race([
        ждемГотово,
        Promise.all(задачи),
        new Promise(function (разрешить) { setTimeout(разрешить, параметры.мсВсего); })
    ]);
    общийСтоп.abort();
    if (пауза) {
        clearTimeout(пауза);
    }
    return {
        варианты: уникальныеСейчас().slice(0, параметры.максимум),
        пояснениеНаправления: пояснениеНаправления,
        ошибки: ошибки
    };
}

