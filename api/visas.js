function парыРежимов() {
    const пары = [];
    function добавить(список, режим) {
        список.forEach(function (маркер) {
            пары.push({ маркер: сжатьМесто(маркер), режим: режим });
        });
    }
    добавить(НУЖНА_ВИЗА, РЕЖИМ_ВИЗА);
    добавить(ОНЛАЙН, РЕЖИМ_ОНЛАЙН);
    добавить(ПО_ПРИБЫТИИ, РЕЖИМ_ПРИБЫТИЕ);
    добавить(БЕЗ_ВИЗ, РЕЖИМ_БЕЗ_ВИЗ);
    пары.sort(function (а, б) { return б.маркер.length - а.маркер.length; });
    return пары;
}

const ПАРЫ = парыРежимов();

function естьМаркер(сжатый, маркер) {
    if (!сжатый || !маркер) {
        return false;
    }
    if (маркер.length <= 4) {
        return сжатый === маркер ||
            сжатый.indexOf(маркер) === 0 ||
            сжатый.lastIndexOf(маркер) === сжатый.length - маркер.length;
    }
    return сжатый.indexOf(маркер) !== -1;
}

function первоеСовпадение(текст) {
    const сжатый = сжатьМесто(текст);
    if (!сжатый) {
        return null;
    }
    for (let i = 0; i < ПАРЫ.length; i++) {
        if (естьМаркер(сжатый, ПАРЫ[i].маркер)) {
            return ПАРЫ[i];
        }
    }
    return null;
}

export function нормализоватьРежимыВизы(список) {
    const набор = [];
    (Array.isArray(список) ? список : []).forEach(function (сырой) {
        let режим = String(сырой || '').trim();
        if (режим === 'Я готов оформить визу') {
            режим = РЕЖИМ_ГОТОВ;
        }
        if (режим && набор.indexOf(режим) === -1) {
            набор.push(режим);
        }
    });
    return {
        набор: набор,
        всеРазрешены: набор.indexOf(РЕЖИМ_ГОТОВ) !== -1,
        пусто: набор.length === 0
    };
}

export function пропускатьФильтрВизы(режимы) {
    return нормализоватьРежимыВизы(режимы).всеРазрешены;
}

export function режимВъезда(текст) {
    const пара = первоеСовпадение(текст);
    return пара ? пара.режим : РЕЖИМ_ВИЗА;
}

export function въездРазрешён(текст, режимы) {
    const описание = нормализоватьРежимыВизы(режимы);
    if (описание.всеРазрешены) {
        return true;
    }
    const разрешённые = описание.пусто ? [РЕЖИМ_БЕЗ_ВИЗ] : описание.набор;
    const режим = режимВъезда(текст);
    if (!режим || режим === РЕЖИМ_ВИЗА) {
        return false;
    }
    return разрешённые.indexOf(режим) !== -1;
}

function местаЭтапов(вариант) {
    const места = [];
    ((вариант && вариант.этапы) || []).forEach(function (этап) {
        const сырое = String((этап && этап.место) || '').trim();
        if (!сырое) {
            return;
        }
        const сжатое = сжатьМесто(сырое);
        if (!сжатое || сжатое === 'москва' || сжатое.indexOf('москва') === 0) {
            return;
        }
        места.push(сырое);
    });
    return места;
}

export function вариантСоответствуетВизам(вариант, режимы) {
    if (пропускатьФильтрВизы(режимы)) {
        return true;
    }
    const места = местаЭтапов(вариант);
    if (места.length === 0) {
        return false;
    }
    return места.every(function (место) {
        return въездРазрешён(место, режимы);
    });
}

export function отфильтроватьВариантыПоВизам(варианты, режимы) {
    if (!Array.isArray(варианты)) {
        return [];
    }
    if (пропускатьФильтрВизы(режимы)) {
        return варианты;
    }
    return варианты.filter(function (вариант) {
        return вариантСоответствуетВизам(вариант, режимы);
    });
}

export function слотРазрешёнПоВизам(слот, режимы) {
    const маркер = String((слот && слот.маркер) || '');
    const роль = String((слот && слот.роль) || '');
    const текст = первоеСовпадение(маркер) ? маркер : роль;
    return въездРазрешён(текст, режимы);
}

export function отфильтроватьСлотыПоВизам(наборы, режимы) {
    if (!наборы) {
        return { основные: [], запас: [] };
    }
    if (пропускатьФильтрВизы(режимы)) {
        return наборы;
    }
    return {
        основные: (наборы.основные || []).filter(function (слот) { return слотРазрешёнПоВизам(слот, режимы); }),
        запас: (наборы.запас || []).filter(function (слот) { return слотРазрешёнПоВизам(слот, режимы); })
    };
}

export function текстПоясненияВизы(направление, режимы) {
    if (пропускатьФильтрВизы(режимы)) {
        return '';
    }
    const описание = нормализоватьРежимыВизы(режимы);
    const список = описание.пусто ? [РЕЖИМ_БЕЗ_ВИЗ] : описание.набор;
    let текст = 'Учтены визовые правила для паспорта РФ по всему миру, не только Шенген: Европа, Азия, Африка, Америка, Ближний Восток и Океания. В выдаче только страны с режимом: ' +
        список.join(', ') +
        '. Куда гражданину РФ нужна заранее оформленная виза — на любом континенте — не предлагается.';
    const сжатый = сжатьМесто(направление);
    if (сжатый.indexOf('европ') !== -1) {
        текст += ' Для Европы без визы это Балканы, не Испания, Франция, Греция или Кипр.';
    }
    return текст;
}
